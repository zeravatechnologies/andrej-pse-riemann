#!/usr/bin/env python3
"""Collect every interface string that goes through tr() into
app/pse_r/i18n_strings.py (round 3, item 23). Run after GUI text changes."""
import ast, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "app" / "pse_r"
sys.path.insert(0, str(ROOT.parent))
def collect() -> list:
    found = set()
    for p in sorted(ROOT.rglob("*.py")):
        if p.name.startswith("i18n"):
            continue
        t = ast.parse(p.read_text(encoding="utf-8"))
        for n in ast.walk(t):
            if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id == "tr" \
                    and n.args and isinstance(n.args[0], ast.Constant) and isinstance(n.args[0].value, str):
                found.add(n.args[0].value)
    # data shown through tr(variable): tab names, palette, providers, "no AI" lists, billing
    src = (ROOT / "gui" / "main_window.py").read_text(encoding="utf-8")
    t = ast.parse(src)
    for n in ast.walk(t):
        if isinstance(n, ast.Dict):
            ks = [k.value for k in n.keys if isinstance(k, ast.Constant) and isinstance(k.value, str)]
            if any(" — " in k for k in ks):
                found.update(ks)
        if isinstance(n, ast.Tuple) and len(n.elts) == 2 and isinstance(n.elts[1], ast.Constant) \
                and isinstance(n.elts[1].value, str) and isinstance(n.elts[0], ast.Attribute) \
                and n.elts[0].attr.startswith("tab_"):
            found.add(n.elts[1].value)
    from pse_r.llm import providers as P
    from pse_r import setup_flow as SF
    for pr in P.PRESETS.values():
        found.update({pr.label, pr.note, pr.better, pr.worse})
    for p in P.PRESETS:
        found.add(P.billing_advice(p)["text"])
    for v in SF.NO_AI_TEXT.values():
        found.update(v)
    # Faza 6d: data labels shown through tr(variable)
    from pse_r.shared_lib import queue_groups as QG
    found.update(QG.KIND_LABEL.values()); found.add(QG.ONE_BY_ONE_REASON)
    found.update({"operater", "agent", "skeptik", "sistem"})
    found.update({"radi", "❄ zamrznuta", "⏳ mjera čeka"})
    from pse_r.shared_lib import ideas as IDEAS
    found.update(IDEAS.STATUS_OF.values()); found.update(IDEAS.ACTIONS.values())
    found.update({"kandidat", "prikazana", "nema"})
    from pse_r.guardian import host as HOST
    found.update(why for _n, _l, why in HOST._WELL_KNOWN.values())
    found.add("nepoznat servis sluša prema mreži")
    from pse_r.pse import agents as AG
    for m, *_r in AG.AGENTS.values():
        found.update({m.state, m.action, m.outcome})
    from pse_r.gui import pse_lab as PL
    found.update(PL.DOC_STATUS.values()); found.update({"tiho", "zvuk", "već-bilo"})
    from pse_r.lab import runner as LR
    for e in LR.catalog():
        found.update({e["title"], e["question"], e["why"], e["cost"]})
        found.update(p["help"] for p in e["params"] if p["help"])
    return sorted(s for s in found if s.strip())


if __name__ == "__main__":
    found = collect()
    out = ROOT / "i18n_strings.py"
    out.write_text('"""Generated by tools/i18n_collect.py — every interface string that is translated."""\n'
                   "STRINGS = " + json.dumps(found, ensure_ascii=False, indent=0) + "\n", encoding="utf-8")
    print(len(found), "strings →", out)
